#!/usr/bin/env bash

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

usage() {
    cat <<'EOF'
Run a plain Codex EdgeBench task with the repository's validated local plumbing.

Usage:
  ./scripts/run_codex_only.sh

Common environment variables:
  TASK                            Task ID (default: vliw_kernel_optimization)
  MODEL                           Codex model (default: gpt-5.5)
  TIMEOUT_SECONDS                 Agent budget (default: 7200)
  EVAL_INTERVAL                   Host auto-eval interval (default: 300)
  RUN_ID                          Unique run ID (generated by default)
  JUDGE_URL                       Container-visible Judge URL
                                  (default: http://host.docker.internal:8080)
  WORK_CPU_LIMIT                  Work CPU limit (default: 4)
  JUDGE_CPU_LIMIT                 Judge CPU limit (default: 3)
  SFORGE_CODEX_REASONING_EFFORT   Codex reasoning effort (default: medium)
  SFORGE_CODEX_AUTH_FILE          Host auth.json (default: ~/.codex/auth.json)
  SFORGE_CODEX_RUNTIME_ARCHIVE    Optional Linux x64 Codex runtime archive
  SFORGE_PYTHON                   Python executable with SForge installed

Example: six-hour Terra VLIW run
  MODEL=gpt-5.6-terra \
  TIMEOUT_SECONDS=21600 \
  SFORGE_CODEX_REASONING_EFFORT=medium \
  ./scripts/run_codex_only.sh

This launcher always selects --agent codex and --enable-internet. It does not
install or invoke Goal Plus.
EOF
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    usage
    exit 0
fi
if (( $# > 0 )); then
    printf 'Unexpected argument: %s\n\n' "$1" >&2
    usage >&2
    exit 2
fi

adapt_proxy_for_container() {
    local proxy_url="$1"
    proxy_url="${proxy_url//127.0.0.1/host.docker.internal}"
    proxy_url="${proxy_url//localhost/host.docker.internal}"
    printf '%s' "$proxy_url"
}

require_positive_integer() {
    local name="$1"
    local value="$2"
    if [[ ! "$value" =~ ^[1-9][0-9]*$ ]]; then
        printf '%s must be a positive integer, got: %s\n' "$name" "$value" >&2
        exit 2
    fi
}

if [[ -z "${DOCKER_HOST:-}" ]]; then
    docker_host="$(docker context inspect "$(docker context show)" \
        --format '{{.Endpoints.docker.Host}}')"
    if [[ -n "$docker_host" ]]; then
        export DOCKER_HOST="$docker_host"
    fi
fi

host_http_proxy="${SFORGE_HTTP_PROXY:-${HTTP_PROXY:-${http_proxy:-}}}"
host_https_proxy="${SFORGE_HTTPS_PROXY:-${HTTPS_PROXY:-${https_proxy:-}}}"
if [[ -n "$host_http_proxy" ]]; then
    export SFORGE_HTTP_PROXY="$(adapt_proxy_for_container "$host_http_proxy")"
fi
if [[ -n "$host_https_proxy" ]]; then
    export SFORGE_HTTPS_PROXY="$(adapt_proxy_for_container "$host_https_proxy")"
fi

export SFORGE_NODEJS_MIRROR_URL="${SFORGE_NODEJS_MIRROR_URL:-https://npmmirror.com/mirrors/node}"
export SFORGE_NPM_REGISTRY_URL="${SFORGE_NPM_REGISTRY_URL:-https://registry.npmmirror.com}"
export SFORGE_CODEX_AUTH_FILE="${SFORGE_CODEX_AUTH_FILE:-$HOME/.codex/auth.json}"
export SFORGE_CODEX_REASONING_EFFORT="${SFORGE_CODEX_REASONING_EFFORT:-medium}"

task="${TASK:-vliw_kernel_optimization}"
model="${MODEL:-gpt-5.5}"
timeout_seconds="${TIMEOUT_SECONDS:-7200}"
eval_interval="${EVAL_INTERVAL:-300}"
judge_url="${JUDGE_URL:-http://host.docker.internal:8080}"
work_cpu_limit="${WORK_CPU_LIMIT:-4}"
judge_cpu_limit="${JUDGE_CPU_LIMIT:-3}"

if [[ -z "$task" || -z "$model" ]]; then
    printf 'TASK and MODEL must both be non-empty\n' >&2
    exit 2
fi

require_positive_integer TIMEOUT_SECONDS "$timeout_seconds"
require_positive_integer EVAL_INTERVAL "$eval_interval"
require_positive_integer WORK_CPU_LIMIT "$work_cpu_limit"
require_positive_integer JUDGE_CPU_LIMIT "$judge_cpu_limit"

model_slug="$(printf '%s' "$model" | tr -cs '[:alnum:]' '-')"
task_slug="$(printf '%s' "$task" | tr -cs '[:alnum:]' '-')"
model_slug="${model_slug%-}"
task_slug="${task_slug%-}"
run_id="${RUN_ID:-codex-${model_slug}-plain-${task_slug}-$(date '+%Y%m%d-%H%M%S')}"

if [[ -n "${SFORGE_PYTHON:-}" ]]; then
    python_bin="$SFORGE_PYTHON"
elif [[ -x "$repo_root/.venv/bin/python" ]]; then
    python_bin="$repo_root/.venv/bin/python"
else
    python_bin="$(command -v python3)"
fi

test -s "$SFORGE_CODEX_AUTH_FILE"
docker info >/dev/null
"$python_bin" -c 'import sforge' >/dev/null

host_judge_url="${judge_url/host.docker.internal/127.0.0.1}"
if command -v curl >/dev/null 2>&1; then
    curl -fsS --max-time 3 "${host_judge_url%/}/openapi.json" >/dev/null
fi

runtime_note="npm fallback"
if [[ "${SFORGE_CODEX_RUNTIME_ARCHIVE+x}" == "x" ]]; then
    runtime_archive="$SFORGE_CODEX_RUNTIME_ARCHIVE"
    if [[ -n "$runtime_archive" && ! -f "$runtime_archive" ]]; then
        printf 'SFORGE_CODEX_RUNTIME_ARCHIVE does not exist: %s\n' \
            "$runtime_archive" >&2
        exit 2
    fi
else
    runtime_archive="$HOME/.cache/sforge/codex/codex-0.144.1-linux-x64.tgz"
fi
if [[ -n "$runtime_archive" && -f "$runtime_archive" ]]; then
    runtime_note="$runtime_archive"
fi

printf 'Run ID: %s\n' "$run_id"
printf 'Agent: codex (plain; Goal Plus disabled)\n'
printf 'Task: %s\n' "$task"
printf 'Model: %s; reasoning effort: %s\n' "$model" "$SFORGE_CODEX_REASONING_EFFORT"
printf 'Budget: %ss; auto-eval: %ss; CPU work/judge: %s/%s\n' \
    "$timeout_seconds" "$eval_interval" "$work_cpu_limit" "$judge_cpu_limit"
printf 'Judge: %s\n' "$judge_url"
printf 'Codex Linux runtime: %s\n' "$runtime_note"

exec "$python_bin" -m sforge run \
    --task "$task" \
    --agent codex \
    --model "$model" \
    --timeout "$timeout_seconds" \
    --eval-interval "$eval_interval" \
    --judge-url "$judge_url" \
    --run-id "$run_id" \
    --enable-internet \
    --work-cpu-limit "$work_cpu_limit" \
    --judge-cpu-limit "$judge_cpu_limit"
